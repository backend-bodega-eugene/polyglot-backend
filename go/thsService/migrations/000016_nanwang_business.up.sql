CREATE TABLE nanwang_scopes (
 kind VARCHAR(24) NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 PRIMARY KEY(kind,owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE nanwang_records (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 kind VARCHAR(24) NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL DEFAULT 0,
 payload JSON NOT NULL,
 version VARCHAR(32) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
 KEY idx_nanwang_scope(kind,owner_id,id),
 CONSTRAINT fk_nanwang_scope FOREIGN KEY(kind,owner_id) REFERENCES nanwang_scopes(kind,owner_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE nanwang_audits (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 record_id BIGINT UNSIGNED NOT NULL,
 kind VARCHAR(24) NOT NULL,
 owner_id BIGINT UNSIGNED NOT NULL,
 admin_id BIGINT UNSIGNED NULL,
 action VARCHAR(24) NOT NULL,
 before_payload JSON NULL,
 after_payload JSON NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 KEY idx_nanwang_audit(kind,owner_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
