CREATE TABLE apk_download_state (
 id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 stored_name VARCHAR(100) NOT NULL DEFAULT '',
 version_name VARCHAR(100) NOT NULL DEFAULT '',
 release_notes TEXT NOT NULL,
 size_bytes BIGINT NOT NULL DEFAULT 0,
 sha256 VARCHAR(64) NOT NULL DEFAULT '',
 passcode_hash VARCHAR(100) NOT NULL DEFAULT '',
 uploaded_at DATETIME(3) NULL,
 updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT INTO apk_download_state(id,release_notes) VALUES (1,'');
CREATE TABLE apk_download_audits (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 admin_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(32) NOT NULL,
 version_name VARCHAR(100) NOT NULL,
 sha256 VARCHAR(64) NOT NULL,
 created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
